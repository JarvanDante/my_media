-- 短剧 zip 分片上传会话与持久化异步导入任务。仅源码提交，不在此环境执行。
-- +goose Up
CREATE TABLE drama_import_upload (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         varchar(16)  NOT NULL,
    filename     varchar(512) NOT NULL DEFAULT '',
    total_size   bigint       NOT NULL,
    chunk_size   bigint       NOT NULL,
    part_count   int          NOT NULL,
    bucket       varchar(128) NOT NULL,
    prefix       varchar(512) NOT NULL,
    pack_key     varchar(512) NOT NULL DEFAULT '',
    status       varchar(16)  NOT NULL DEFAULT 'uploading',
    job_code     varchar(16)  NOT NULL DEFAULT '',
    plan_json    text         NOT NULL DEFAULT '',
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now(),
    expires_at   timestamptz  NOT NULL,
    completed_at timestamptz
);
CREATE UNIQUE INDEX uk_drama_import_upload_code ON drama_import_upload (code);
CREATE INDEX idx_drama_import_upload_status ON drama_import_upload (status, expires_at);
COMMENT ON TABLE drama_import_upload IS '短剧 zip 分片上传会话（临时对象前缀 drama/import/{code}/）';

CREATE TABLE drama_import_part (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upload_id   bigint       NOT NULL REFERENCES drama_import_upload (id) ON DELETE CASCADE,
    n           int          NOT NULL,
    size        bigint       NOT NULL,
    object_key  varchar(512) NOT NULL,
    uploaded_at timestamptz
);
CREATE UNIQUE INDEX uk_drama_import_part ON drama_import_part (upload_id, n);
COMMENT ON TABLE drama_import_part IS '短剧 zip 分片元数据，完成时按会话校验大小与完整性';

CREATE TABLE drama_import_job (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         varchar(16)  NOT NULL,
    upload_id    bigint       NOT NULL REFERENCES drama_import_upload (id),
    upload_code  varchar(16)  NOT NULL,
    bucket       varchar(128) NOT NULL,
    pack_key     varchar(512) NOT NULL,
    plan_json    text         NOT NULL DEFAULT '',
    status       varchar(16)  NOT NULL DEFAULT 'queued',
    stage        varchar(32)  NOT NULL DEFAULT 'queued',
    progress     int          NOT NULL DEFAULT 0,
    message      text         NOT NULL DEFAULT '',
    error        text         NOT NULL DEFAULT '',
    result_json  text         NOT NULL DEFAULT '',
    attempts     int          NOT NULL DEFAULT 0,
    max_attempts int          NOT NULL DEFAULT 3,
    heartbeat_at timestamptz,
    started_at   timestamptz,
    finished_at  timestamptz,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_drama_import_job_code ON drama_import_job (code);
CREATE UNIQUE INDEX uk_drama_import_job_upload ON drama_import_job (upload_id);
CREATE INDEX idx_drama_import_job_status ON drama_import_job (status, id);
COMMENT ON TABLE drama_import_job IS '短剧 zip 异步导入任务；逐集转码仍走原 Kafka/transcode_job';

-- +goose Down
DROP TABLE IF EXISTS drama_import_job;
DROP TABLE IF EXISTS drama_import_part;
DROP TABLE IF EXISTS drama_import_upload;
