CREATE TABLE drama_import_job_item (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id      bigint       NOT NULL REFERENCES drama_import_job (id) ON DELETE CASCADE,
    item_key    varchar(512) NOT NULL,
    drama_code  varchar(16)  NOT NULL,
    explicit    boolean      NOT NULL DEFAULT false,
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uk_drama_import_job_item ON drama_import_job_item (job_id, item_key);
COMMENT ON TABLE drama_import_job_item IS '短剧导入任务项与整部资产的持久绑定；item_key 为压缩包规范目录，不用可编辑标题';
COMMENT ON COLUMN drama_import_job_item.item_key IS '规范目录标识（如 . 或 目录名或 parent/目录），同一任务内唯一';
COMMENT ON COLUMN drama_import_job_item.drama_code IS '已绑定的短剧整部对外短码';
COMMENT ON COLUMN drama_import_job_item.explicit IS '是否来自计划中显式指定的 target_id';

